const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'..'),c=vm.createContext({window:{}});
for(const f of ['workout-intel.js','intel-equipment.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),c);
const data=c.window.WORKOUT_INTEL.days,api=c.window.WorkoutEquipment,plain=v=>JSON.parse(JSON.stringify(v));
const hammer=plain(api.stations(data['2026-10-15']));
assert.equal(hammer.length,9);
assert.deepEqual(hammer[0].equipment,['Гантели']);
assert.deepEqual(hammer[1].equipment,['Диск']);
assert.deepEqual(hammer[2].equipment,['Гантели','Скамья']);
assert.deepEqual(hammer[4].equipment,['Штанга']);
assert.deepEqual(hammer[5].equipment,['Турник','Резина для турника','Резина']);
assert.deepEqual(hammer[6].equipment,['YBell × 2','Степ']);
assert.deepEqual(hammer[7].equipment,['Гиря','Бокс']);
assert.deepEqual(hammer[8].equipment,['GHR','Место на полу']);
assert.deepEqual(plain(api.combine(['Гантель','Гантели','Гантель'])),['Гантели']);
assert.deepEqual(plain(api.combine(['  гантель ','ГАНТЕЛИ','Гантель'])),['Гантели']);
assert.deepEqual(plain(api.combine(['Гиря','Гири','Диск','Диски','Штанги','Штанга'])),['Гиря','Диск','Штанга']);
assert.deepEqual(plain(api.summary(data['2026-10-12'])),['Гантели','Гиря','Диск']);
assert.deepEqual(plain(api.combine(['Гантель'])),['Гантели']);
assert.equal(api.summary(data['2026-10-15']).filter(x=>x==='YBell').length,1);
assert(!api.summary(data['2026-10-15']).includes('YBell × 2'));
assert.deepEqual(plain(api.combine(['YBell','Два  YBell'])),['YBell × 2']);
assert.equal(api.summary(data['2026-10-13']).length,0);
assert.deepEqual(plain(api.combine(['YBell','Два YBell','Два YBell'])),['YBell × 2']);
assert.deepEqual(plain(api.combine(['Без оборудования','Без оборудования'])),['Без инвентаря']);
assert.equal(api.stations(data['2026-10-12']).length,18);
assert.equal(api.stations(data['2026-10-14']).length,12);
assert.equal(api.stations(data['2026-10-13']).length,0);
assert.equal(api.stations(null).length,0);
assert.equal(api.tomorrow(new Date('2026-10-11T12:00:00Z')),'2026-10-12');
assert.equal(api.tomorrow(new Date('2026-10-11T21:30:00Z')),'2026-10-13');
assert.equal(api.tomorrow(new Date('2026-12-31T12:00:00Z')),'2027-01-01');
assert.equal(api.tomorrow(new Date('2028-02-28T12:00:00Z')),'2028-02-29');
assert.equal(api.tomorrow(new Date('2026-10-31T12:00:00Z')),'2026-11-01');
for(const x of hammer)assert(x.equipment.every(x=>!x.toLowerCase().includes('pause')));
console.log('PASS equipment checks: per-station union, supports, explicit quantities, no-inventory, pending dates and Moscow tomorrow rollover');
